"""Build "Mac2Win KVM.app" so the desktop app shows its own name and icon.

Run with:  uv run make_app.py            (installs into ~/Applications)
           uv run make_app.py --dest DIR

The bundle does not copy the code: its launcher runs `uv sync` in this checkout
and starts kvm_app.py from here, so `git pull` updates the app. The Python
interpreter is copied into Contents/MacOS under the app's name, which makes
macOS (Dock, Cmd+Tab, menu bar, Activity Monitor, Force Quit) show
"Mac2Win KVM" instead of "Python".
"""

import argparse
import os
import plistlib
import shlex
import shutil
import sys
from pathlib import Path

APP_NAME = "Mac2Win KVM"
BUNDLE_ID = "com.nfelsen.mac2win-kvm"
REPO = Path(__file__).resolve().parent


def info_plist(name=APP_NAME, bundle_id=BUNDLE_ID, version="1.0"):
    return {
        "CFBundleName": name,
        "CFBundleDisplayName": name,
        "CFBundleIdentifier": bundle_id,
        "CFBundleExecutable": "launcher",
        "CFBundleIconFile": "icon.icns",
        "CFBundlePackageType": "APPL",
        "CFBundleShortVersionString": version,
        "CFBundleVersion": version,
        "LSMinimumSystemVersion": "11.0",
        "NSHighResolutionCapable": True,
        "NSHumanReadableCopyright": "github.com/nfelsen/mac-to-windows-keyboard",
    }


def launcher_script(repo, uv, name=APP_NAME):
    """Shell launcher: sync the venv, refresh the bundled interpreter, exec it."""
    q = shlex.quote
    return f"""#!/bin/bash
# Generated by make_app.py; rerun it after moving the checkout.
REPO={q(str(repo))}
UV={q(str(uv))}
CONTENTS="$(cd "$(dirname "$0")/.." && pwd)"
BIN="$CONTENTS/MacOS/{name}"
LOG="$HOME/Library/Logs/{name}.log"
exec >>"$LOG" 2>&1
echo "--- $(date) starting {name}"
cd "$REPO" || exit 1
"$UV" sync --quiet || exit 1
REAL="$("$REPO/.venv/bin/python3" -c 'import os, sys; print(os.path.realpath(sys.executable))')" || exit 1
HOME_DIR="$(dirname "$REAL")"
VERSION="$(basename "$REAL" | sed 's/^python//')"
# The interpreter loads @executable_path/../lib/libpython*.dylib and finds the
# venv's site-packages through Contents/pyvenv.cfg and Contents/lib.
if ! cmp -s "$REAL" "$BIN"; then cp -f "$REAL" "$BIN"; fi
mkdir -p "$CONTENTS/lib"
for dylib in "$HOME_DIR"/../lib/libpython*.dylib; do ln -sfn "$dylib" "$CONTENTS/lib/$(basename "$dylib")"; done
ln -sfn "$REPO/.venv/lib/python$VERSION" "$CONTENTS/lib/python$VERSION"
printf 'home = %s\\ninclude-system-site-packages = false\\nversion = %s\\n' "$HOME_DIR" "$VERSION" >"$CONTENTS/pyvenv.cfg"
exec "$BIN" "$REPO/kvm_app.py"
"""


def find_uv():
    for candidate in (os.environ.get("UV"), shutil.which("uv"), Path.home() / ".local/bin/uv"):
        if candidate and Path(candidate).is_file():
            return Path(candidate).resolve()
    raise SystemExit("uv not found; install it or run this with `uv run make_app.py`")


def build(dest, repo=REPO, uv=None, name=APP_NAME):
    app = Path(dest).expanduser() / f"{name}.app"
    contents = app / "Contents"
    if app.exists():
        shutil.rmtree(app)
    (contents / "MacOS").mkdir(parents=True)
    (contents / "Resources").mkdir()
    with open(contents / "Info.plist", "wb") as f:
        plistlib.dump(info_plist(name), f)
    icon = repo / "assets" / "icon.icns"
    if icon.is_file():
        shutil.copy2(icon, contents / "Resources" / "icon.icns")
    launcher = contents / "MacOS" / "launcher"
    launcher.write_text(launcher_script(repo, uv or find_uv(), name))
    launcher.chmod(0o755)
    return app


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dest", default="~/Applications", help="Folder to install into (default: ~/Applications)")
    args = parser.parse_args(argv)
    app = build(args.dest)
    print(f"Built {app}")
    print(f"Open it with:  open {shlex.quote(str(app))}")
    print(f"Logs:          ~/Library/Logs/{APP_NAME}.log")
    return 0


if __name__ == "__main__":
    sys.exit(main())
